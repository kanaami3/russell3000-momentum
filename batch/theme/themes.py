# 相対力の基準。TOPIX連動ETF。
BENCHMARK = "1306.T"


def all_tickers() -> list[str]:
    """重複を除いた全銘柄（yfinance 用に .T を付ける）。"""
    codes = {code for rows in THEME_BASKETS.values() for code, _ in rows}
    return sorted(f"{c}.T" for c in codes) + [BENCHMARK]


def name_of(code: str) -> str:
    for rows in THEME_BASKETS.values():
        for c, n in rows:
            if c == code:
                return n
    return code
